export const state = { lang: prefs.get("jaddati.language") || "en" };

export const isAr = () => state.lang === "ar";

/** Look up an interface string. */
export function L(english) {
  if (state.lang !== "ar") return english;
  return AR[english] ?? english;
}

export function setLang(lang) {
  state.lang = lang;
  prefs.set("jaddati.language", lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}

export function toggleLang() { setLang(state.lang === "ar" ? "en" : "ar"); }

/** Good-enough script detection, matching TextDirection.isArabic in the app. */
export function isArabicText(s) {
  if (!s) return false;
  for (const ch of s) {
    const v = ch.codePointAt(0);
    if ((v >= 0x0600 && v <= 0x06FF) || (v >= 0x0750 && v <= 0x077F) ||
        (v >= 0xFB50 && v <= 0xFDFF) || (v >= 0xFE70 && v <= 0xFEFF)) return true;
  }
  return false;
}

/** Direction for one run of text, independent of the paragraph around it. */
export const dirOf = (s) => (isArabicText(s) ? "rtl" : "ltr");

// ── Counts ──────────────────────────────────────────────────────────────
// Arabic counted nouns change with the number. CLDR gets the plural category
// right; what it cannot do is pick the noun, so these are written out.

export const Counts = {
  number(v) {
    return new Intl.NumberFormat(state.lang === "ar" ? "ar" : "en").format(v);
  },
  originals(n) {
    if (!isAr()) return n === 1 ? "1 original recording" : `${this.number(n)} original recordings`;
    if (n === 1) return "تسجيل أصلي واحد";
    if (n === 2) return "تسجيلان أصليان";
    if (n >= 3 && n <= 10) return `${this.number(n)} تسجيلات أصلية`;
    return `${this.number(n)} تسجيلًا أصليًا`;
  },
  savedClips(n) {
    if (!isAr()) return n === 1 ? "1 saved clip" : `${this.number(n)} saved clips`;
    if (n === 1) return "مقطع محفوظ واحد";
    if (n === 2) return "مقطعان محفوظان";
    if (n >= 3 && n <= 10) return `${this.number(n)} مقاطع محفوظة`;
    return `${this.number(n)} مقطعًا محفوظًا`;
  },
  books(n) {
    if (!isAr()) return n === 1 ? "1 book" : `${this.number(n)} books`;
    if (n === 1) return "كتاب واحد";
    if (n === 2) return "كتابان";
    if (n >= 3 && n <= 10) return `${this.number(n)} كتب`;
    return `${this.number(n)} كتابًا`;
  },
  sealed(n) {
    if (!isAr()) return n === 1 ? "1 sealed letter" : `${this.number(n)} sealed letters`;
    if (n === 1) return "رسالة مختومة واحدة";
    if (n === 2) return "رسالتان مختومتان";
    if (n >= 3 && n <= 10) return `${this.number(n)} رسائل مختومة`;
    return `${this.number(n)} رسالة مختومة`;
  },
  pagesRead(read, total) {
    if (!isAr()) return `${this.number(read)} of ${this.number(total)} pages read`;
    const pages = total >= 3 && total <= 10 ? "صفحات" : "صفحة";
    return `قُرئت ${this.number(read)} من ${this.number(total)} ${pages}`;
  },
  pagePosition(page, total) {
    return isAr()
      ? `صفحة ${this.number(page)} من ${this.number(total)}`
      : `Page ${this.number(page)} of ${this.number(total)}`;
  },
  /**
   * "0 / 800", and it has to stay in that order.
   *
   * Right-to-left, the bidi algorithm reorders a bare "0 / 800" into "800 / 0",
   * so the limit sits where the count belongs and an empty box appears to have
   * a limit of zero. Isolating the pair as left-to-right pins it. This affects
   * every compose screen in the app, not only the newest ones.
   */
  characters(used, limit) {
    const pair = `${this.number(used)} / ${this.number(limit)}`;
    return isAr() ? `\u2066${pair}\u2069` : pair;
  },
  duration(seconds) {
    if (!(seconds > 0)) return L("Duration");
    const total = Math.round(seconds);
    const m = Math.floor(total / 60), s = total % 60;
    if (isAr()) return m > 0 ? `${this.number(m)} د ${this.number(s)} ث` : `${this.number(s)} ثانية`;
    return m > 0 ? `${m}m ${s}s` : `${total}s`;
  },
  clock(seconds) {
    if (!Number.isFinite(seconds) || seconds < 0) return "0:00";
    const t = Math.round(seconds);
    return `${Math.floor(t / 60)}:${String(t % 60).padStart(2, "0")}`;
  },
};
